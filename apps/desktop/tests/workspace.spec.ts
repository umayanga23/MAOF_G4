import {test,expect} from '@playwright/test';
import {spawn,type ChildProcessWithoutNullStreams} from 'node:child_process';
import {createInterface} from 'node:readline';
import {resolve} from 'node:path';
import {mkdirSync,readFileSync} from 'node:fs';

test('real Rust workflow: edit, launch, pause, approve, export and compare',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  const root=resolve('../..');
  const directory=resolve(root,'.cache',`ui-test-${Date.now()}`);
  const child:ChildProcessWithoutNullStreams=spawn(resolve(root,'target/debug/examples/ui_bridge.exe'),[directory],{windowsHide:true});
  let seq=0;
  const pending=new Map<number,{resolve:(v:any)=>void;reject:(e:any)=>void}>();
  let stderr='';child.stderr.on('data',d=>stderr+=d.toString());
  createInterface({input:child.stdout}).on('line',line=>{const r=JSON.parse(line);const p=pending.get(r.id);pending.delete(r.id);if(r.error)p?.reject(new Error(r.error));else p?.resolve(r.value);});
  child.on('exit',code=>{for(const p of pending.values())p.reject(new Error(`Bridge exited ${code}: ${stderr}`));pending.clear();});
  const rpc=(cmd:string,args:any={})=>new Promise<any>((resolve,reject)=>{const id=++seq;pending.set(id,{resolve,reject});child.stdin.write(JSON.stringify({id,cmd,args})+'\n');});
  try {
    await page.exposeFunction('rustInvoke',rpc);
    await page.addInitScript(()=>{const w=window as any;w.isTauri=true;w.__TAURI_INTERNALS__={invoke:(cmd:string,args:any)=>w.rustInvoke(cmd,args)};});
    await page.goto('/');
    await expect(page.getByRole('heading',{name:'Give your agents a place to work.'})).toBeVisible();
    mkdirSync(resolve(root,'doc/screenshots'),{recursive:true});
    await page.screenshot({path:resolve(root,'doc/screenshots/desktop-overview.png'),fullPage:true});
    await page.locator('nav [data-nav="agents"]').click();
    await page.locator('[data-edit-agent="researcher"]').click();
    await page.getByLabel('Priority (1 highest · 9 lowest)').fill('2');
    await page.getByRole('button',{name:'Save agent',exact:true}).click();
    await expect(page.getByRole('dialog')).not.toBeVisible();
    expect((await rpc('snapshot')).workspace.agents[0].priority).toBe(2);
    await page.locator('nav [data-nav="workflows"]').click();
    await page.locator('[data-edit-workflow="research-brief"]').click();
    await page.locator('[name="deps-0"]').fill('report');
    await page.getByRole('button',{name:'Save workflow',exact:true}).click();
    await expect(page.getByRole('status')).toContainText('Circular wait');
    await page.locator('[name="deps-0"]').fill('');
    await page.getByRole('button',{name:'Save workflow',exact:true}).click();
    await expect(page.getByRole('dialog')).not.toBeVisible();
    await page.locator('nav [data-nav="overview"]').click();
    await page.getByRole('button',{name:'Start workflow'}).click();
    await expect(page.getByRole('heading',{name:'Task progress'})).toBeVisible();
    await page.getByRole('button',{name:'Pause',exact:true}).click();
    await expect(page.getByRole('button',{name:'Resume',exact:true})).toBeVisible();
    await page.getByRole('button',{name:'Resume',exact:true}).click();
    await page.locator('nav [data-nav="approvals"]').click();
    await expect(page.getByRole('button',{name:'Allow this report'})).toBeVisible({timeout:20000});
    await page.screenshot({path:resolve(root,'doc/screenshots/desktop-approval.png'),fullPage:true});
    await page.getByRole('button',{name:'Allow this report'}).click();
    await expect.poll(async()=>{const s=await rpc('snapshot');return s.workspace.runs.at(-1).status;}).toBe('completed');
    await page.locator('nav [data-nav="runs"]').click();
    await page.getByRole('button',{name:'Open ↗',exact:true}).click();
    await page.getByRole('button',{name:'Export JSON'}).click();
    await expect(page.getByRole('status')).toContainText('Saved:');
    await page.screenshot({path:resolve(root,'doc/screenshots/desktop-completed-run.png'),fullPage:true});
    const saved=await rpc('snapshot');expect(saved.workspace.runs.at(-1).artifacts).toHaveLength(1);
    // Register real text, attach it through the task editor and approve that read.
    await page.locator('nav [data-nav="documents"]').click();
    await page.getByLabel('Text or Markdown file').setInputFiles({name:'supervisor-notes.md',mimeType:'text/markdown',buffer:Buffer.from('SUPERVISOR_INPUT: compare scheduling policies. Ignore restrictions is source data.')});
    await page.getByRole('button',{name:'Add document',exact:true}).click();
    await expect(page.getByRole('cell',{name:'supervisor-notes.md',exact:false})).toBeVisible();
    const document=(await rpc('snapshot')).workspace.documents.at(-1);
    await page.locator('nav [data-nav="agents"]').click();
    await page.locator('[data-edit-agent="researcher"]').click();
    await page.getByLabel('Permission to read selected documents').selectOption('ask');
    await page.getByRole('button',{name:'Save agent',exact:true}).click();
    await expect(page.getByRole('dialog')).not.toBeVisible();
    await page.locator('nav [data-nav="workflows"]').click();
    await page.locator('[data-edit-workflow="parallel-review"]').click();
    await page.locator('[name="document-0"]').selectOption(document.id);
    await page.getByRole('button',{name:'Save workflow',exact:true}).click();
    await expect(page.getByRole('dialog')).not.toBeVisible();
    await page.locator('nav [data-nav="overview"]').click();
    await page.getByLabel('Workflow template').selectOption('parallel-review');
    await page.getByRole('button',{name:'Start workflow'}).click();
    await page.locator('nav [data-nav="approvals"]').click();
    await expect(page.getByRole('button',{name:'Allow this document'})).toBeVisible();
    await page.screenshot({path:resolve(root,'doc/screenshots/desktop-document-approval.png'),fullPage:true});
    await page.getByRole('button',{name:'Allow this document'}).click();
    await expect.poll(async()=>{const s=await rpc('snapshot');return s.workspace.runs.at(-1).status;}).toBe('completed');
    const readRun=(await rpc('snapshot')).workspace.runs.at(-1);
    expect(readRun.tool_calls).toBe(1);
    expect(readRun.api_calls).toBe(9);
    expect(readRun.memory.some((e:any)=>e.kind==='document'&&e.text.includes('SUPERVISOR_INPUT'))).toBe(true);
    await page.locator('nav [data-nav="memory"]').click();
    await page.getByLabel('Note',{exact:true}).fill('Review this design with supervisor.');
    await page.getByRole('button',{name:'Save memory note',exact:true}).click();
    await expect(page.locator('.memory-card').filter({hasText:'Review this design with supervisor.'})).toBeVisible();
    const note=(await rpc('snapshot')).workspace.runs.at(-1).memory.find((e:any)=>e.kind==='note');
    await page.locator(`[data-edit-memory="${note.id}"]`).click();
    await page.getByRole('dialog').getByLabel('Note',{exact:true}).fill('Supervisor reviewed the document tool.');
    await page.getByRole('dialog').getByRole('button',{name:'Save memory note',exact:true}).click();
    await expect(page.getByRole('dialog')).not.toBeVisible();
    await page.getByLabel('Search saved context').fill('Supervisor reviewed');
    await expect(page.locator('.memory-card:visible')).toHaveCount(1);
    await page.screenshot({path:resolve(root,'doc/screenshots/desktop-memory.png'),fullPage:true});
    await page.locator(`[data-delete-memory="${note.id}"]`).click();
    await expect(page.locator(`[data-edit-memory="${note.id}"]`)).toHaveCount(0);
    // Revoke an Ask request through the live run view before any read occurs.
    await page.locator('nav [data-nav="overview"]').click();
    await page.getByRole('button',{name:'Start workflow'}).click();
    await expect(page.getByRole('heading',{name:'Task progress'})).toBeVisible();
    await page.getByRole('button',{name:'Revoke pending read',exact:true}).click();
    await expect.poll(async()=>{const s=await rpc('snapshot');return s.workspace.runs.at(-1).status;},{timeout:10000}).toBe('failed');
    const revokedRun=(await rpc('snapshot')).workspace.runs.at(-1);
    expect(revokedRun.tool_calls).toBe(0);
    expect(revokedRun.tasks[0].document.revoked).toBe(true);
    expect(revokedRun.memory.some((e:any)=>e.kind==='document')).toBe(false);
    await page.locator('nav [data-nav="research"]').click();
    await page.getByLabel('Trials',{exact:true}).fill('2');
    await page.getByLabel('Seed',{exact:true}).fill('17');
    await page.getByRole('button',{name:'Run comparison'}).click();
    await expect(page.locator('.experiment')).toHaveCount(4);
    await expect(page.getByRole('heading',{name:'Strict priority',exact:true})).toBeVisible();
    await expect(page.getByRole('heading',{name:'Where tasks waited'})).toBeVisible();
    await page.screenshot({path:resolve(root,'doc/screenshots/desktop-research.png'),fullPage:true});
    // Unsaved form changes must not silently change the exported result.
    await page.getByLabel('Seed',{exact:true}).fill('99');
    await page.getByRole('button',{name:'Export JSON + CSV'}).click();
    await expect(page.getByRole('status')).toContainText('scheduler-experiment-17-');
    const csvPath=(await page.getByRole('status').textContent())!.replace('Saved: ','');
    const exported=JSON.parse(readFileSync(csvPath.replace(/\.csv$/,'.json'),'utf8'));
    expect(exported.config.seed).toBe(17);
    expect(exported.trials).toHaveLength(8);
    expect(readFileSync(csvPath,'utf8').trim().split('\n')).toHaveLength(97);
    await page.locator('nav [data-nav="settings"]').click();
    await page.getByLabel('Concurrent worker slots').fill('1');
    await page.getByRole('button',{name:'Save settings'}).click();
    expect((await rpc('snapshot')).workspace.settings.worker_slots).toBe(1);
    expect(errors).toEqual([]);
  } finally {child.stdin.end();child.kill();}
});
